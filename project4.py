import turtle
t = turtle.Turtle()

t.speed(10)
t.penup()
t.goto(-100, -40)
t.color("blue")
#made the 6 blue
t.pendown()
turtle.Screen().bgcolor("teal")
t.width(10)

t.circle(40)
t.setheading(-180)
for i in range(40):
    t.forward(5)
    t.right(5)
#making the 6
t.penup()
t.goto(0, 80)
#moving to the 7
t.color("navy")
t.pendown()
t.setheading(0)
t.forward(80)
t.setheading(-110)
t.forward(130)
#making the 7
turtle.exitonclick()

